"""Independent CDDL outcomes: pycddl's Rust engine; never imports MoonBit.

Cases are handwritten semantic partitions, not claims of full RFC conformance.
Binary fixtures are generated by cbor2, not by the runtime codec under test.
"""
from pathlib import Path
import json
import sys
from importlib.metadata import version
import cbor2
from pycddl import Schema, ValidationError

ROOT = Path(__file__).resolve().parents[1]


def cases():
    out = []

    def add(label, source, valid, invalid):
        for expected, values in [(True, valid), (False, invalid)]:
            for value in values:
                out.append((label, source, value, expected))

    add('signed integers', 'root = int', [0, -1, 7, 2**63-1, -(2**63)], [False, None, '1', 1.5, [], {}])
    add('unsigned integers', 'root = uint', [0, 1, 255], [-1, True, '1', 0.25])
    add('negative integers', 'root = nint', [-1, -20], [0, 1, -0.5])
    add('closed range', 'root = -2..3', [-2, 0, 3], [-3, 4, True, 2.5])
    add('half open range', 'root = 0...3', [0, 2], [-1, 3, 2.5])
    add('text byte size', 'root = tstr .size 3', ['cat', '猫'], ['', 'a', '🐱', 'é'])
    add('text size interval', 'root = tstr .size (1..4)', ['a', '猫', '🐱'], ['', 'abcde'])
    add('byte size', 'root = bstr .size 2', [b'ab', b'\x00\xff'], [b'', b'a', 'ab'])
    add('uint capacity', 'root = uint .size 1', [0, 1, 255], [-1, 256, True])
    add('literal choice', 'root = "on" / "off" / nil', ['on', 'off', None], ['', True, 1])
    add('boolean type', 'root = bool', [True, False], [0, 1, None])
    add('float type', 'root = float', [1.25, -0.5], [1, '1.25', None])
    add('ordered tuple', 'root = [uint, tstr, bool]', [[1, 'x', True]], [[], [1, 'x'], ['x', 1, True], [1, 'x', True, 2]])
    add('repeat and required tail', 'root = [* int, int]', [[1], [1, 2, 3]], [[], [False]])
    add('optional and required tail', 'root = [? int, int]', [[1], [1, 2]], [[], [1, 2, 3]])
    add('bounded repeat', 'root = [2*3 uint]', [[0, 1], [0, 1, 2]], [[], [0], [0, 1, 2, 3], [0, -1]])
    add('one or more', 'root = [+ bool]', [[True], [False, True]], [[], [True, 0]])
    add('closed record', 'root = {id: uint, ? label: tstr}', [{'id': 1}, {'label': 'x', 'id': 0}], [{}, {'id': -1}, {'id': 1, 'extra': 0}, {'id': 1, 'label': 2}])
    add('typed keys', 'root = {1: tstr, ? 2: bstr}', [{1: 'a'}, {1: 'a', 2: b'x'}], [{}, {1: 'a', 2: 'x'}, {'1': 'a'}])
    add('open dictionary', 'root = {* tstr => uint}', [{}, {'x': 1, 'y': 2}], [{'x': -1}, {1: 0}])
    add('bounded dictionary', 'root = {1*2 tstr => uint}', [{'x': 1}, {'a': 1, 'b': 2}], [{}, {'a': 1, 'b': 2, 'c': 3}])
    add('mixed dictionary', 'root = {id: uint, * tstr => tstr}', [{'id': 1}, {'id': 1, 'x': 'y'}], [{'id': 1, 'x': 2}, {'x': 'y'}])
    add('reference', 'root = [level, level] level = 0..3 / "auto"', [[1, 'auto']], [[4, 'auto'], ['auto']])
    add('recursive tree', 'root = int / [* root]', [1, [], [1, [2, []]]], [None, [1, [False]]])
    add('tagged bytes', 'root = #6.18(bstr .size 2)', [cbor2.CBORTag(18, b'ab')], [b'ab', cbor2.CBORTag(18, b'a'), cbor2.CBORTag(19, b'ab')])
    add('nested service message', 'root = {version: 1, readings: [1*4 reading]} reading = {id: uint, value: int / nil}', [{'version': 1, 'readings': [{'id': 2, 'value': -4}]}], [{'version': 2, 'readings': []}, {'version': 1, 'readings': [{'id': '2', 'value': 0}]}])
    return out


def main():
    assert version('pycddl') == '0.6.4'
    assert version('cbor2') == '5.6.5'
    records = []
    disagreements = []
    for i, (label, source, value, expected) in enumerate(cases()):
        encoded = cbor2.dumps(value)
        validator = Schema(source)
        try:
            validator.validate_cbor(encoded)
            actual = True
        except ValidationError:
            actual = False
        if actual != expected:
            disagreements.append({'id': i, 'label': label, 'value': repr(value), 'specified': expected, 'oracle': actual})
        records.append({'id': i, 'label': label, 'schema': source, 'hex': encoded.hex(), 'expected': expected, 'referenceActual': actual})
    document = {'oracle': 'pycddl==0.6.4 (Rust CDDL), cbor2==5.6.5 encoder', 'profile': 'rfc8610-structural-v1', 'referenceDeviations': disagreements, 'cases': records}
    # Explicitly frozen deviations, not a blanket exemption for a changing oracle.
    assert [d['id'] for d in disagreements] == [20, 21, 23, 24, 25, 50, 54, 80, 83, 84, 126], 'new or changed reference deviation requires normative review'
    output = json.dumps(document, indent=2, ensure_ascii=False) + '\n'
    destination = ROOT / 'fixtures' / 'reference.json'
    if '--check' in sys.argv:
        assert destination.read_text(encoding='utf8') == output, 'independent fixture drift'
    else:
        destination.parent.mkdir(exist_ok=True)
        destination.write_text(output, encoding='utf8', newline='\n')
    print(f'Independent Rust CDDL oracle: {len(records)} cases, deviations from specified partitions: {disagreements}')


if __name__ == '__main__':
    main()
